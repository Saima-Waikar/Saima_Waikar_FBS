#1.Numeric Data type
#int 
var = 10
print(type(var))

#float
var = 3.14
print(type(var))

#Complex
var = 10+5j
print(type(var))

#2.Sequential Data type
#list
var = [10,20,30,40]
print(type(var))

#tuple
var = (10,20,30,40)
print(type(var))

#range
var = range(1,10)
print(type(var))

#3.Set type 
#set
var = {10,20,30,40}
print(type(var))

#frozen set
var = frozenset({10,20,30})
print(type(var))

#mapping (Dictonary)
var = {'id':101, 'name':'xyz'}
print(type(var))

#other data type
#boolean
var = True
print(type(var))

#nonetype
var = None
print(type(var))